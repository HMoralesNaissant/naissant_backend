package com.naissant.naissantapp.Controller;

import com.naissant.naissantapp.Entity.InvoicesDetail;
import com.naissant.naissantapp.Service.InvoicesDetailService;
import com.naissant.naissantapp.domain.ResponseDto;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.*;

@RestController
@RequestMapping({"/invoicesDetail"})
@CrossOrigin(origins = "http://localhost:4200", maxAge = 3600)

public class InvoicesDetailController {

    @Autowired
    InvoicesDetailService service;

    private final Logger LOG = LoggerFactory.getLogger(InvoicesDetailController.class);

    @GetMapping
    public ResponseEntity listar() {
        try {
            return ResponseEntity.ok(new ResponseDto(service.listar(), true));
        } catch (Exception e) {
            LOG.error("No se pudo completar ", e);
            return ResponseEntity.internalServerError()
                    .body(new ResponseDto("No se pudo completar", false));
        }
    }
    
    @PostMapping
    public ResponseEntity agregar(@RequestBody InvoicesDetail i) {
        try {
            return ResponseEntity.ok(new ResponseDto(service.add(i), true));
        } catch (Exception e) {
            LOG.error("No se pudo completar ", e);
            return ResponseEntity.internalServerError()
                    .body(new ResponseDto("No se pudo completar", false));
        }
    }
    
    @GetMapping(path = {"/{id}"})
    public ResponseEntity listarId(@PathVariable("id") int id) {
        try {
            return ResponseEntity.ok(new ResponseDto(service.listarId(id), true));
        } catch (Exception e) {
            LOG.error("No se pudo completar ", e);
            return ResponseEntity.internalServerError()
                    .body(new ResponseDto("No se pudo completar", false));
        }
    }
        
    @PutMapping(path = {"/{id}"})
    public ResponseEntity editar(@RequestBody InvoicesDetail i, @PathVariable("id") int id) {
        try {
            i.setId(id);
            return ResponseEntity.ok(new ResponseDto(service.edit(i), true));
        } catch (Exception e) {
            LOG.error("No se pudo completar ", e);
            return ResponseEntity.internalServerError()
                    .body(new ResponseDto("No se pudo completar", false));
        }
    }
    
    @GetMapping(path = {"/findByInvoice/{id_invoice}"})
    public ResponseEntity listarByIdInvoice(@PathVariable("id_invoice") int id_invoice) {
        try {
            return ResponseEntity.ok(new ResponseDto(service.listarByIdInvoice(id_invoice), true));
        } catch (Exception e) {
            LOG.error("No se pudo completar ", e);
            return ResponseEntity.internalServerError()
                    .body(new ResponseDto("No se pudo completar", false));
        }
    }
}
