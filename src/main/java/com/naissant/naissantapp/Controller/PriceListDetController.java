package com.naissant.naissantapp.Controller;

import com.naissant.naissantapp.Entity.PriceListDet;
import com.naissant.naissantapp.Service.PriceListDetService;
import com.naissant.naissantapp.domain.ResponseDto;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.CrossOrigin;
import org.springframework.web.bind.annotation.PathVariable;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.PutMapping;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RestController;

@RestController
@RequestMapping({"/pricelistdet"})
@CrossOrigin(origins = "http://localhost:4200", maxAge = 3600)

public class PriceListDetController {

    @Autowired
    PriceListDetService service;

    private final Logger LOG = LoggerFactory.getLogger(PriceListDetController.class);

    @GetMapping
    public ResponseEntity listar() {
        try {
            return ResponseEntity.ok(new ResponseDto(service.listar(), true));
        } catch (Exception e) {
            LOG.error("No se pudo completar ", e);
            return ResponseEntity.internalServerError()
                    .body(new ResponseDto("No se pudo completar", false));
        }
    }
    
    @PostMapping
    public ResponseEntity agregar(@RequestBody PriceListDet p) {
        try {
            return ResponseEntity.ok(new ResponseDto(service.add(p), true));
        } catch (Exception e) {
            LOG.error("No se pudo completar ", e);
            return ResponseEntity.internalServerError()
                    .body(new ResponseDto("No se pudo completar", false));
        }
    }
    
    @GetMapping(path = {"/{id}"})
    public ResponseEntity listarId(@PathVariable("id") int id) {
        try {
            return ResponseEntity.ok(new ResponseDto(service.listarId(id), true));
        } catch (Exception e) {
            LOG.error("No se pudo completar ", e);
            return ResponseEntity.internalServerError()
                    .body(new ResponseDto("No se pudo completar", false));
        }
    }
        
    @PutMapping(path = {"/{id}"})
    public ResponseEntity editar(@RequestBody PriceListDet p, @PathVariable("id") int id) {
        try {
            p.setId(id);
            return ResponseEntity.ok(new ResponseDto(service.edit(p), true));
        } catch (Exception e) {
            LOG.error("No se pudo completar ", e);
            return ResponseEntity.internalServerError()
                    .body(new ResponseDto("No se pudo completar", false));
        }
    }
    
    @GetMapping(path = {"/findByList/{id_list}"})
    public ResponseEntity listarByIdList(@PathVariable("id_list") int id_list) {
        try {
            return ResponseEntity.ok(new ResponseDto(service.listarByIdList(id_list), true));
        } catch (Exception e) {
            LOG.error("No se pudo completar ", e);
            return ResponseEntity.internalServerError()
                    .body(new ResponseDto("No se pudo completar", false));
        }
    }
    
    @GetMapping(path = {"/findByCatproducts/{id_catproducts}"})
    public ResponseEntity listarByIdCatproducts(@PathVariable("id_catproducts") int id_catproducts) {
        try {
            return ResponseEntity.ok(new ResponseDto(service.listarByIdCatproducts(id_catproducts), true));
        } catch (Exception e) {
            LOG.error("No se pudo completar ", e);
            return ResponseEntity.internalServerError()
                    .body(new ResponseDto("No se pudo completar", false));
        }
    }
    
    @GetMapping(path = {"/findByProduct/{id_product}"})
    public ResponseEntity listarByIdProduct(@PathVariable("id_product") int id_product) {
        try {
            return ResponseEntity.ok(new ResponseDto(service.listarByIdProduct(id_product), true));
        } catch (Exception e) {
            LOG.error("No se pudo completar ", e);
            return ResponseEntity.internalServerError()
                    .body(new ResponseDto("No se pudo completar", false));
        }
    }
        
}
