package com.naissant.naissantapp.Controller;

import com.naissant.naissantapp.Entity.Reportados;
import com.naissant.naissantapp.Service.ReportadosService;
import com.naissant.naissantapp.domain.ResponseDto;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.*;

@RestController
@RequestMapping({"/reportados"})
@CrossOrigin(origins = "http://localhost:4200", maxAge = 3600)

public class ReportadosController {

    @Autowired
    ReportadosService service;

    private final Logger LOG = LoggerFactory.getLogger(ReportadosController.class);

    @GetMapping
    public ResponseEntity listar() {
        try {
            return ResponseEntity.ok(new ResponseDto(service.listar(), true));
        } catch (Exception e) {
            LOG.error("No se pudo completar ", e);
            return ResponseEntity.internalServerError()
                    .body(new ResponseDto("No se pudo completar", false));
        }
    }
    
    @PostMapping
    public ResponseEntity agregar(@RequestBody Reportados r) {
        try {
            return ResponseEntity.ok(new ResponseDto(service.add(r), true));
        } catch (Exception e) {
            LOG.error("No se pudo completar ", e);
            return ResponseEntity.internalServerError()
                    .body(new ResponseDto("No se pudo completar", false));
        }
    }
    
    @GetMapping(path = {"/{id}"})
    public ResponseEntity listarId(@PathVariable("id") int id) {
        try {
            return ResponseEntity.ok(new ResponseDto(service.listarId(id), true));
        } catch (Exception e) {
            LOG.error("No se pudo completar ", e);
            return ResponseEntity.internalServerError()
                    .body(new ResponseDto("No se pudo completar", false));
        }
    }
    
    @PutMapping(path = {"/{id}"})
    public ResponseEntity editar(@RequestBody Reportados r, @PathVariable("id") int id) {
        try {
            r.setId(id);
            return ResponseEntity.ok(new ResponseDto(service.edit(r), true));
        } catch (Exception e) {
            LOG.error("No se pudo completar ", e);
            return ResponseEntity.internalServerError()
                    .body(new ResponseDto("No se pudo completar", false));
        }
    }
    
    @GetMapping(path = {"/findByPersona/{id_persona}"})
    public ResponseEntity listarByIdPersona(@PathVariable("id_persona") int id_persona) {
        try {
            return ResponseEntity.ok(new ResponseDto(service.listarByIdPersona(id_persona), true));
        } catch (Exception e) {
            LOG.error("No se pudo completar ", e);
            return ResponseEntity.internalServerError()
                    .body(new ResponseDto("No se pudo completar", false));
        }
    }

}
