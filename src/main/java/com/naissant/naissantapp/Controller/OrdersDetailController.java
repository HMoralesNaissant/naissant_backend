package com.naissant.naissantapp.Controller;

import com.naissant.naissantapp.Entity.OrdersDetail;
import com.naissant.naissantapp.Service.OrdersDetailService;
import com.naissant.naissantapp.domain.ResponseDto;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.CrossOrigin;
import org.springframework.web.bind.annotation.PathVariable;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.PutMapping;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RestController;

@RestController
@RequestMapping({"/ordersdetail"})
@CrossOrigin(origins = "http://localhost:4200", maxAge = 3600)

public class OrdersDetailController {

    @Autowired
    OrdersDetailService service;

    private final Logger LOG = LoggerFactory.getLogger(OrdersDetailController.class);

    @GetMapping
    public ResponseEntity listar() {
        try {
            return ResponseEntity.ok(new ResponseDto(service.listar(), true));
        } catch (Exception e) {
            LOG.error("No se pudo completar ", e);
            return ResponseEntity.internalServerError()
                    .body(new ResponseDto("No se pudo completar", false));
        }
    }
    
    @PostMapping
    public ResponseEntity agregar(@RequestBody OrdersDetail o) {
        try {
            return ResponseEntity.ok(new ResponseDto(service.add(o), true));
        } catch (Exception e) {
            LOG.error("No se pudo completar ", e);
            return ResponseEntity.internalServerError()
                    .body(new ResponseDto("No se pudo completar", false));
        }
    }
    
    @GetMapping(path = {"/{id}"})
    public ResponseEntity listarId(@PathVariable("id") int id) {
        try {
            return ResponseEntity.ok(new ResponseDto(service.listarId(id), true));
        } catch (Exception e) {
            LOG.error("No se pudo completar ", e);
            return ResponseEntity.internalServerError()
                    .body(new ResponseDto("No se pudo completar", false));
        }
    }
        
    @PutMapping(path = {"/{id}"})
    public ResponseEntity editar(@RequestBody OrdersDetail o, @PathVariable("id") int id) {
        try {
            o.setId(id);
            return ResponseEntity.ok(new ResponseDto(service.edit(o), true));
        } catch (Exception e) {
            LOG.error("No se pudo completar ", e);
            return ResponseEntity.internalServerError()
                    .body(new ResponseDto("No se pudo completar", false));
        }
    }
    
    @GetMapping(path = {"/findByOrderHeader/{id_order_header}"})
    public ResponseEntity listarByIdOrderHeader(@PathVariable("id_order_header") int id_order_header) {
        try {
            return ResponseEntity.ok(new ResponseDto(service.listarByIdOrderHeader(id_order_header), true));
        } catch (Exception e) {
            LOG.error("No se pudo completar ", e);
            return ResponseEntity.internalServerError()
                    .body(new ResponseDto("No se pudo completar", false));
        }
    }
    
    @GetMapping(path = {"/findByProduct/{id_product}"})
    public ResponseEntity listarByIdProduct(@PathVariable("id_product") int id_product) {
        try {
            return ResponseEntity.ok(new ResponseDto(service.listarByIdProduct(id_product), true));
        } catch (Exception e) {
            LOG.error("No se pudo completar ", e);
            return ResponseEntity.internalServerError()
                    .body(new ResponseDto("No se pudo completar", false));
        }
    }
}
